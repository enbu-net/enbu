// recordingTransport records the command code of every command sent to the
// TPM, and the size of the caller-supplied sensitive data of each Create.
type recordingTransport struct {
	next transport.TPMCloser

	mu        sync.Mutex
	commands  []tpm2.TPMCC
	sensitive []int
}

func (r *recordingTransport) Send(command []byte) ([]byte, error) {
	r.record(command)
	return r.next.Send(command)
}

func (r *recordingTransport) record(command []byte) {
	r.mu.Lock()
	defer r.mu.Unlock()
	if len(command) < 10 {
		r.commands = append(r.commands, 0)
		return
	}
	code := tpm2.TPMCC(binary.BigEndian.Uint32(command[6:10]))
	r.commands = append(r.commands, code)
	if code == tpm2.TPMCCCreate {
		r.sensitive = append(r.sensitive, createSensitiveSize(command))
	}
}

func (r *recordingTransport) Close() error { return r.next.Close() }

func (r *recordingTransport) sent() []tpm2.TPMCC {
	r.mu.Lock()
	defer r.mu.Unlock()
	return slices.Clone(r.commands)
}

// createSensitiveSize returns the length of inSensitive.data in a TPM2_Create
// command: header (10), parent handle (4), authorization area, then
// TPM2B_SENSITIVE_CREATE { size, userAuth, data }. It returns -1 when the
// command does not have that layout, so a check for 0 cannot pass by mistake.
func createSensitiveSize(command []byte) int {
	if len(command) < 18 || tpm2.TPMISTCommandTag(binary.BigEndian.Uint16(command[0:2])) != tpm2.TPMSTSessions {
		return -1
	}
	p := 18 + int(binary.BigEndian.Uint32(command[14:18])) + 2
	if p < 18 || len(command) < p+2 {
		return -1
	}
	p += 2 + int(binary.BigEndian.Uint16(command[p:]))
	if len(command) < p+2 {
		return -1
	}
	return int(binary.BigEndian.Uint16(command[p:]))
}

// importSoftwareKey generates a P-256 key in software and imports it under the
// storage primary with the given public template, as a tool that "moves an
// existing key into the TPM" would. It returns the imported blobs.
func importSoftwareKey(t *testing.T, b *TPMBackend, template tpm2.TPMTPublic) (tpm2.TPM2BPublic, tpm2.TPM2BPrivate, error) {
	t.Helper()
	c, err := b.acquire()
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = b.release(c) }()
	c.mu.Lock()
	defer c.mu.Unlock()
	kem, err := tpm2.ImportEncapsulationKey(&c.public)
	if err != nil {
		t.Fatal(err)
	}
	key, err := ecdh.P256().GenerateKey(rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	point := key.PublicKey().Bytes()
	template.Unique = tpm2.NewTPMUPublicID(tpm2.TPMAlgECC, &tpm2.TPMSECCPoint{
		X: tpm2.TPM2BECCParameter{Buffer: point[1:33]}, Y: tpm2.TPM2BECCParameter{Buffer: point[33:]}})
	name, err := tpm2.ObjectName(&template)
	if err != nil {
		t.Fatal(err)
	}
	sensitive := tpm2.Marshal(tpm2.TPMTSensitive{SensitiveType: tpm2.TPMAlgECC,
		Sensitive: tpm2.NewTPMUSensitiveComposite(tpm2.TPMAlgECC, &tpm2.TPM2BECCParameter{Buffer: key.Bytes()})})
	duplicate, seed, err := tpm2.CreateDuplicate(rand.Reader, kem, name.Buffer, sensitive)
	if err != nil {
		t.Fatal(err)
	}
	public := tpm2.New2B(template)
	imported, err := (tpm2.Import{
		ParentHandle: c.parentAuth(),
		ObjectPublic: public, Duplicate: tpm2.TPM2BPrivate{Buffer: duplicate},
		InSymSeed: tpm2.TPM2BEncryptedSecret{Buffer: seed}, Symmetric: tpm2.TPMTSymDef{Algorithm: tpm2.TPMAlgNull},
	}).Execute(c.t)
	if err != nil {
		return tpm2.TPM2BPublic{}, tpm2.TPM2BPrivate{}, err
	}
	return public, imported.OutPrivate, nil
}

// importable clears the attributes a TPM requires to be clear on TPM2_Import:
// a key that came from outside cannot claim it was generated inside.
func importable(template tpm2.TPMTPublic) tpm2.TPMTPublic {
	template.ObjectAttributes.FixedTPM = false
	template.ObjectAttributes.FixedParent = false
	template.ObjectAttributes.SensitiveDataOrigin = false
	return template
}

// Both keys are generated by the TPM: enbu sends TPM2_Create with no
// sensitive data, never imports a key, and every decryption and signature
// runs on the TPM the backend opened.
func TestTPMKeysAreGeneratedAndUsedInTheTPM(t *testing.T) {
	rec := &recordingTransport{next: &virtualTransport{newVirtualTPM(t)}}
	b := &TPMBackend{Device: "test", plainSessions: true, Open: func() (transport.TPMCloser, error) { return rec, nil }}
	md := &Metadata{}
	key, s, err := b.Create(md)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = key.Close(); _ = s.Close() }()

	created := rec.sent()
	for _, forbidden := range []tpm2.TPMCC{tpm2.TPMCCImport, tpm2.TPMCCLoadExternal, tpm2.TPMCCDuplicate} {
		if slices.Contains(created, forbidden) {
			t.Fatalf("Create sent %v, which includes %v", created, forbidden)
		}
	}
	if !slices.Equal(rec.sensitive, []int{0, 0}) {
		t.Fatalf("TPM2_Create carried caller sensitive data of sizes %v, want the TPM to generate both keys", rec.sensitive)
	}
	for _, obj := range []TPMObject{md.TPM.ECDH, md.TPM.Sign} {
		public, err := tpm2.Unmarshal[tpm2.TPM2BPublic](obj.Public)
		if err != nil {
			t.Fatal(err)
		}
		pub, err := public.Contents()
		if err != nil {
			t.Fatal(err)
		}
		if a := pub.ObjectAttributes; !a.FixedTPM || !a.FixedParent || !a.SensitiveDataOrigin {
			t.Fatalf("key attributes = %+v, want fixedTPM, fixedParent and sensitiveDataOrigin", a)
		}
	}

	peer, err := ecdh.P256().GenerateKey(rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	before := len(rec.sent())
	if _, err := key.ECDH(peer.PublicKey()); err != nil {
		t.Fatal(err)
	}
	if !slices.Contains(rec.sent()[before:], tpm2.TPMCCECDHZGen) {
		t.Fatal("ECDH did not run ECDH_ZGen on the TPM")
	}
	before = len(rec.sent())
	sig, err := s.Sign(signing.DomainState, []byte("state"))
	if err != nil {
		t.Fatal(err)
	}
	if err := signing.Verify(s.Public(), signing.DomainState, []byte("state"), sig); err != nil {
		t.Fatal(err)
	}
	if !slices.Contains(rec.sent()[before:], tpm2.TPMCCSign) {
		t.Fatal("signing did not run TPM2_Sign on the TPM")
	}
}

// A key generated outside the TPM and imported is refused even though the TPM
// itself would use it.
func TestTPMRefusesImportedSoftwareKeys(t *testing.T) {
	b := newTPMBackend(t)
	ecdhPub, err := ecdhTemplate()
	if err != nil {
		t.Fatal(err)
	}
	// Pin the real primary, so only the template check stands between the
	// imported blob and a key the TPM would load.
	parent := primaryName(t, b)
	for _, template := range []tpm2.TPMTPublic{ecdhPub, signTemplate()} {
		public, private, err := importSoftwareKey(t, b, importable(template))
		if err != nil {
			t.Fatalf("import: %v", err)
		}
		pub, err := public.Contents()
		if err != nil {
			t.Fatal(err)
		}
		name, err := tpm2.ObjectName(pub)
		if err != nil {
			t.Fatal(err)
		}
		obj := TPMObject{Public: tpm2.Marshal(public), Private: tpm2.Marshal(private), Name: name.Buffer}
		if l, err := b.load(parent, obj, template); err == nil {
			_ = l.close()
			t.Fatal("loaded an imported software key")
		}
	}
}

// Keys are bound to the TPM that generated them: another TPM cannot load them.
func TestTPMKeyDoesNotLoadOnAnotherTPM(t *testing.T) {
	d, md := newTPMDevice(t, newTPMBackend(t))
	_ = d.Close()
	if _, _, err := newTPMBackend(t).Load(md); err == nil {
		t.Fatal("another TPM loaded the keys")
	}
}

// primaryName returns the Name of the storage primary b uses.
func primaryName(t *testing.T, b *TPMBackend) []byte {
	t.Helper()
	c, err := b.acquire()
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = b.release(c) }()
	return append([]byte(nil), c.name.Buffer...)
}
