func TestTPMNativeLifecycle(t *testing.T) {
	if os.Getenv("ENBU_TEST_NATIVE_IDENTITY") != "1" {
		t.Skip("set ENBU_TEST_NATIVE_IDENTITY=1 on a TPM 2.0 device")
	}
	b := platformHardware()
	if d := b.Probe(); !d.Available {
		t.Fatalf("native hardware unavailable: %+v", d)
	}
	id, md, err := b.Create()
	if err != nil {
		t.Fatal(err)
	}
	ct, err := age.EncryptForPublicKeys([]byte("native TPM"), []string{id.Recipient().String()})
	if err != nil {
		t.Fatal(err)
	}
	_ = id.Close()
	loaded, err := b.Load(md)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = loaded.Close() }()
	out, err := age.Decrypt(ct, loaded)
	if err != nil || string(out) != "native TPM" {
		t.Fatalf("native decrypt: %q %v", out, err)
	}
}

// TestTPMNativeKeyOrigin checks, on the real TPM, the properties the identity
// relies on: keys are generated by this TPM's TPM2_Create without caller
// sensitive data, decryption runs on it, and the TPM refuses to import a
// software key that claims fixedTPM. The last one is what makes the template
// check in Load sufficient; the test vTPM does not enforce it.
func TestTPMNativeKeyOrigin(t *testing.T) {
	if os.Getenv("ENBU_TEST_NATIVE_IDENTITY") != "1" {
		t.Skip("set ENBU_TEST_NATIVE_IDENTITY=1 on a TPM 2.0 device")
	}
	native, ok := platformHardware().(*TPMBackend)
	if !ok {
		t.Fatalf("platform hardware is %T, want a TPM", platformHardware())
	}
	if native.Device != "/dev/tpmrm0" && native.Device != "/dev/tpm0" && native.Device != "Windows TBS" {
		t.Fatalf("device = %q, want the host TPM", native.Device)
	}
	// Create opens the TPM more than once, so every connection records into
	// one log.
	rec := &recordingTransport{}
	b := &TPMBackend{Device: native.Device, Open: func() (transport.TPMCloser, error) {
		next, err := native.Open()
		if err != nil {
			return nil, err
		}
		return &sharedRecording{rec: rec, next: next}, nil
	}}
	id, md, err := b.Create()
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = id.Close() }()
	if !slices.Equal(rec.sensitive, []int{0}) {
		t.Fatalf("TPM2_Create carried caller sensitive data of sizes %v", rec.sensitive)
	}
	ct, err := age.EncryptForPublicKeys([]byte("native TPM"), []string{id.Recipient().String()})
	if err != nil {
		t.Fatal(err)
	}
	before := len(rec.sent())
	if out, err := age.Decrypt(ct, id); err != nil || string(out) != "native TPM" {
		t.Fatalf("native decrypt: %q %v", out, err)
	}
	if !slices.Contains(rec.sent()[before:], tpm2.TPMCCECDHZGen) {
		t.Fatal("decryption did not run ECDH_ZGen on the host TPM")
	}
	if md.Device != native.Device {
		t.Fatalf("metadata device = %q, want %q", md.Device, native.Device)
	}

	rec.sensitive = nil
	s, _, err := b.CreateSigner()
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = s.Close() }()
	if !slices.Equal(rec.sensitive, []int{0}) {
		t.Fatalf("signer TPM2_Create carried caller sensitive data of sizes %v", rec.sensitive)
	}
	before = len(rec.sent())
	sig, err := s.Sign(signing.DomainState, []byte("native TPM"))
	if err != nil {
		t.Fatal(err)
	}
	if err := signing.Verify(s.Public(), signing.DomainState, []byte("native TPM"), sig); err != nil {
		t.Fatal(err)
	}
	if !slices.Contains(rec.sent()[before:], tpm2.TPMCCSign) {
		t.Fatal("signing did not run TPM2_Sign on the host TPM")
	}

	template, err := ecdhTemplate()
	if err != nil {
		t.Fatal(err)
	}
	// The TPM must refuse the import because of the attributes, not by accident.
	if _, _, err := importSoftwareKey(t, native, template); err == nil {
		t.Fatal("the TPM imported a software key marked fixedTPM; enbu cannot tell such a key from one the TPM generated")
	} else if !errors.Is(err, tpm2.TPMRCAttributes) {
		t.Fatalf("ECDH import failed with %v, want TPM_RC_ATTRIBUTES", err)
	}
	if _, _, err := importSoftwareKey(t, native, signTemplate()); err == nil {
		t.Fatal("the TPM imported a software signing key marked fixedTPM")
	} else if !errors.Is(err, tpm2.TPMRCAttributes) {
		t.Fatalf("signing import failed with %v, want TPM_RC_ATTRIBUTES", err)
	}
}

// sharedRecording is one TPM connection that records into a shared log.
type sharedRecording struct {
	rec  *recordingTransport
	next transport.TPMCloser
}

func (s *sharedRecording) Send(command []byte) ([]byte, error) {
	s.rec.record(command)
	return s.next.Send(command)
}

func (s *sharedRecording) Close() error { return s.next.Close() }
